export const fabricById = (id: string) => fabrics.find((f) => f.id === id);

/**
 * The fabrics the site offers — in the pickers, on Discover, on the home page:
 * the library less any it holds back (`hidden`), as the sheer chiffon is until
 * sheer cloth can be drawn.
 */
export const offeredFabrics: Fabric[] = fabrics.filter((f) => !f.hidden);

/** The plain black in the library — the black crepe — which a new necktie or bow tie arrives in on a light shirt: see `tieStartOn`. */
export const PLAIN_BLACK = "fb-black-crepe";
/** The plain white — which a new necktie or bow tie arrives in on a dark shirt: see `tieStartOn`. */
export const PLAIN_WHITE = "fb-white";

/**
 * The cloth a new necktie or bow tie arrives in on a shirt cut from `shirt`:
 * black on a light shirt, white on a dark one — navy, black, any dark colour
 * — so a new tie always shows (the user's rule). Whichever of the two stands
 * further from the shirt in lightness (CIE L*, of each one's average colour).
 */
export function tieStartOn(shirt: Fabric): Fabric {
  return furtherOf(shirt);
}

/** Of the plain black and the plain white, the one further from `fabric` in lightness (CIE L*, of each one's average colour). */
function furtherOf(fabric: Fabric): Fabric {
  const lightness = (f: Fabric) => hexToLab(fabricAverageColor(f))[0];
  const [black, white] = [fabricById(PLAIN_BLACK)!, fabricById(PLAIN_WHITE)!];
  const own = lightness(fabric);
  return Math.abs(lightness(white) - own) > Math.abs(lightness(black) - own) ? white : black;
}

/**
 * The plain cloth a collar's stripes arrive in, so they show from the first —
 * stripes cut from the collar's own cloth would not show at all: of the plain
 * white and the plain black, the one further from it in lightness (CIE L*, of
 * each average colour). On dark cloth that is the white, as on a navy sailor
 * collar; on light cloth, the black crepe. They are the lightest and the
 * darkest of the first samples, so this is the choice the whole library once
 * made — now held to the two, so a whiter white or a deeper black added to
 * the library never takes their place.
 */
export function contrastingPlain(fabric: Fabric): Fabric {
  return furtherOf(fabric);
}
